"""Local demo provider: no network, no GPU, no credentials.

It returns templated text that is explicitly labelled as a demo response and simulates
latency from a per-model speed profile. Every request it serves is stored with is_demo=true,
so demo traffic can always be told apart from real traffic.
"""

import asyncio
import hashlib
import random
from collections.abc import Awaitable, Callable
from dataclasses import dataclass

from app.models.enums import ProviderKind
from app.providers.base import (
    CompletionRequest,
    CompletionResult,
    EndpointConfig,
    InferenceProvider,
    estimated_usage,
)
from app.utils.tokens import CHARS_PER_TOKEN

DEMO_RESPONSE_LABEL = "[Demo response — generated by the local demo provider, not by a real model]"
MAX_SIMULATED_LATENCY_SECONDS = 8.0


@dataclass(frozen=True)
class DemoSpeedProfile:
    base_latency_ms: float  # fixed overhead, roughly "time to first token"
    tokens_per_second: float
    jitter: float  # +/- fraction applied to the total latency


DEMO_PROFILES = {
    "swift-1b": DemoSpeedProfile(base_latency_ms=60, tokens_per_second=180, jitter=0.15),
    "orbit-8b": DemoSpeedProfile(base_latency_ms=140, tokens_per_second=85, jitter=0.2),
    "atlas-70b": DemoSpeedProfile(base_latency_ms=380, tokens_per_second=28, jitter=0.25),
}
DEFAULT_PROFILE = DEMO_PROFILES["orbit-8b"]

_PARAGRAPHS = (
    "When this model is connected to a real endpoint, this panel shows the text returned by "
    "that endpoint, and the latency below is measured around the actual HTTP call.",
    "Latency, token counts and throughput for this run are recorded in the request log and "
    "included in Performance Analytics, where they are labelled as demo data.",
    "Token counts for demo responses are estimated from text length (about four characters "
    "per token). Providers that report usage, such as OpenAI-compatible APIs, are stored as exact.",
    "To try a real model, register an OpenAI-compatible, vLLM or Hugging Face endpoint in the "
    "Model Registry and select it here.",
    "Lower temperatures make real models more deterministic; higher values increase variety. "
    "The demo provider ignores temperature and uses a fixed speed profile per model.",
)


class DemoProvider(InferenceProvider):
    kind = ProviderKind.DEMO

    def __init__(
        self,
        simulate_latency: bool = True,
        sleep: Callable[[float], Awaitable[None]] = asyncio.sleep,
    ):
        self._simulate_latency = simulate_latency
        self._sleep = sleep
        self._random = random.Random()

    async def complete(self, endpoint: EndpointConfig, request: CompletionRequest) -> CompletionResult:
        text = compose_demo_response(request.prompt, request.max_tokens)
        usage = estimated_usage(request, text)
        if self._simulate_latency:
            profile = DEMO_PROFILES.get(endpoint.model_identifier, DEFAULT_PROFILE)
            await self._sleep(self._simulated_seconds(profile, usage.completion_tokens))
        return CompletionResult(text=text, usage=usage)

    async def check_health(self, endpoint: EndpointConfig) -> None:
        # Runs in-process, so it is reachable whenever the backend is.
        return None

    def _simulated_seconds(self, profile: DemoSpeedProfile, completion_tokens: int) -> float:
        milliseconds = profile.base_latency_ms + completion_tokens / profile.tokens_per_second * 1000
        milliseconds *= 1 + self._random.uniform(-profile.jitter, profile.jitter)
        return min(milliseconds / 1000, MAX_SIMULATED_LATENCY_SECONDS)


def compose_demo_response(prompt: str, max_tokens: int) -> str:
    snippet = " ".join(prompt.split())[:120]
    if len(prompt) > 120:
        snippet += "…"

    # Pick a stable paragraph order per prompt so repeated runs look consistent.
    # (hashlib rather than hash(), which is randomised per process.)
    prompt_digest = hashlib.sha256(prompt.encode()).hexdigest()
    paragraphs = sorted(
        _PARAGRAPHS, key=lambda paragraph: hashlib.sha256((prompt_digest + paragraph).encode()).digest()
    )

    text = "\n\n".join([DEMO_RESPONSE_LABEL, f'Prompt received: "{snippet}"', *paragraphs])
    # Stay within max_tokens (as estimated), counting the ellipsis that marks truncation.
    max_chars = max_tokens * CHARS_PER_TOKEN
    return text if len(text) <= max_chars else text[: max_chars - 1].rstrip() + "…"
