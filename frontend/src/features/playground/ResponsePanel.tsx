import { AlertTriangle, ArrowUpRight, Clock, MessageSquareText } from 'lucide-react';
import { Link } from 'react-router-dom';

import type { InferenceRecord } from '@/api/types';
import { DemoBadge, TokenSourceBadge } from '@/components/ui/Badge';
import { Card, CardHeader } from '@/components/ui/Card';
import { EmptyState } from '@/components/ui/States';
import { RequestStatusBadge } from '@/components/ui/StatusIndicator';
import { useNow } from '@/hooks/useNow';
import { errorTitle } from '@/lib/errors';
import { formatLatency, formatTokens, formatTokensPerSecond } from '@/lib/format';

interface ResponsePanelProps {
  result: InferenceRecord | null;
  running: boolean;
  startedAt: number | null;
  requestError: string | null;
}

export function ResponsePanel({ result, running, startedAt, requestError }: ResponsePanelProps) {
  return (
    <Card className="flex min-h-96 flex-col" aria-live="polite" aria-busy={running}>
      <CardHeader
        title="Response"
        actions={
          result && !running ? (
            <div className="flex items-center gap-2">
              {result.is_demo && <DemoBadge label="Demo response" />}
              <RequestStatusBadge status={result.status} />
            </div>
          ) : undefined
        }
      />
      <div className="flex flex-1 flex-col px-4 pb-4">
        {running && startedAt ? (
          <Waiting startedAt={startedAt} />
        ) : requestError ? (
          <div role="alert" className="rounded-lg border border-danger/30 bg-danger/10 p-3 text-sm text-red-200">
            {requestError}
          </div>
        ) : result ? (
          <ResultView result={result} />
        ) : (
          <EmptyState
            className="flex-1"
            icon={<MessageSquareText className="size-5" aria-hidden />}
            title="Run a prompt to see the response"
            description="Latency is measured by the backend around the call to the endpoint. Token counts are marked exact when the provider reports them."
          />
        )}
      </div>
    </Card>
  );
}

function Waiting({ startedAt }: { startedAt: number }) {
  const now = useNow(100);
  return (
    <div className="flex flex-1 flex-col items-center justify-center gap-2 text-muted" role="status">
      <Clock className="size-5 animate-pulse" aria-hidden />
      <p className="text-sm">Waiting for the endpoint…</p>
      <p className="font-mono text-xs tabular-nums">{((now - startedAt) / 1000).toFixed(1)} s</p>
    </div>
  );
}

function ResultView({ result }: { result: InferenceRecord }) {
  const metrics = result.metrics;
  return (
    <div className="flex flex-1 flex-col gap-4">
      {result.is_demo && (
        <p className="text-xs text-violet-200">
          Generated by the local demo provider. The text and timing are simulated, not produced by a model.
        </p>
      )}

      {result.status === 'error' ? (
        <div role="alert" className="rounded-lg border border-danger/30 bg-danger/10 p-3">
          <p className="flex items-center gap-2 text-sm font-medium text-red-300">
            <AlertTriangle className="size-4" aria-hidden />
            {errorTitle(result.error_kind)}
            {result.upstream_status_code && <span className="font-mono text-xs">HTTP {result.upstream_status_code}</span>}
          </p>
          <p className="mt-1 text-xs break-words text-red-200">{result.error_message}</p>
        </div>
      ) : (
        <pre className="max-h-[28rem] flex-1 overflow-auto rounded-lg border border-line bg-canvas p-3 font-mono text-xs leading-relaxed break-words whitespace-pre-wrap text-fg">
          {result.response_text || <span className="text-muted">(empty response)</span>}
        </pre>
      )}

      {metrics && (
        <dl className="grid grid-cols-2 gap-3 sm:grid-cols-4">
          <Metric label="Latency" value={formatLatency(metrics.latency_ms)} />
          <Metric label="Prompt tokens" value={formatTokens(metrics.prompt_tokens, metrics.token_count_source)} />
          <Metric label="Completion tokens" value={formatTokens(metrics.completion_tokens, metrics.token_count_source)} />
          <Metric label="Generation speed" value={formatTokensPerSecond(metrics.tokens_per_second)} />
        </dl>
      )}
      {metrics?.token_count_source && (
        <p className="flex items-center gap-2 text-xs text-muted">
          Token counts <TokenSourceBadge source={metrics.token_count_source} />
          {metrics.token_count_source === 'exact'
            ? 'reported by the provider.'
            : 'from text length (~4 characters per token); the provider did not report usage.'}
        </p>
      )}

      <Link
        to={`/logs?request=${result.id}`}
        className="inline-flex items-center gap-1 self-start text-xs font-medium text-blue-300 hover:underline"
      >
        Open in Request Logs
        <ArrowUpRight className="size-3.5" aria-hidden />
      </Link>
    </div>
  );
}

function Metric({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-lg border border-line bg-elevated/40 px-3 py-2">
      <dt className="text-[11px] text-muted">{label}</dt>
      <dd className="mt-1 font-mono text-sm font-semibold tabular-nums">{value}</dd>
    </div>
  );
}
