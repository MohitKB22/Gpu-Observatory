import { screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it } from 'vitest';

import type { InferenceRecord } from '@/api/types';
import { buildModel, mockApi, renderWithProviders, systemInfo } from '@/test/utils';
import PlaygroundPage from './PlaygroundPage';

const demoModel = buildModel({ id: 'demo-1', name: 'demo-swift-1b', provider: 'demo', is_demo: true, endpoint_url: null });
const realModel = buildModel({ id: 'real-1', name: 'gpt-proxy' });
const disabledModel = buildModel({ id: 'off', name: 'disabled-model', is_enabled: false });

function record(overrides: Partial<InferenceRecord>): InferenceRecord {
  return {
    id: 'req-1',
    created_at: new Date().toISOString(),
    model_id: 'demo-1',
    model_name: 'demo-swift-1b',
    provider: 'demo',
    source: 'playground',
    is_demo: true,
    status: 'success',
    prompt: 'Hello',
    system_prompt: null,
    response_text: '[Demo response] Hi there',
    temperature: 0.7,
    max_tokens: 256,
    error_kind: null,
    error_message: null,
    upstream_status_code: null,
    metrics: {
      latency_ms: 812,
      prompt_tokens: 2,
      completion_tokens: 40,
      total_tokens: 42,
      token_count_source: 'estimated',
      tokens_per_second: 49.3,
    },
    ...overrides,
  };
}

function setup(inferenceResult: InferenceRecord) {
  return mockApi({
    'GET /api/system/info': systemInfo,
    'GET /api/models': [demoModel, realModel, disabledModel],
    'GET /api/logs': { items: [], total: 0, page: 1, page_size: 6 },
    'POST /api/inference': inferenceResult,
  });
}

describe('PlaygroundPage', () => {
  it('only offers enabled models', async () => {
    setup(record({}));
    renderWithProviders(<PlaygroundPage />);

    const select = await screen.findByRole('combobox', { name: 'Model' });
    const options = Array.from((select as HTMLSelectElement).options).map((option) => option.text);
    expect(options).toEqual(['demo-swift-1b (demo)', 'gpt-proxy']);
  });

  it('requires a prompt before sending anything', async () => {
    const user = userEvent.setup();
    const { calls } = setup(record({}));
    renderWithProviders(<PlaygroundPage />);

    await user.click(await screen.findByRole('button', { name: 'Run inference' }));

    expect(screen.getByText('Enter a prompt.')).toBeInTheDocument();
    expect(calls.some((call) => call.method === 'POST')).toBe(false);
  });

  it('runs inference and labels a demo response and estimated tokens', async () => {
    const user = userEvent.setup();
    const { calls } = setup(record({}));
    renderWithProviders(<PlaygroundPage />);

    await user.type(await screen.findByRole('textbox', { name: 'Prompt' }), 'Hello');
    await user.click(screen.getByRole('button', { name: 'Run inference' }));

    expect(await screen.findByText('[Demo response] Hi there')).toBeInTheDocument();
    expect(screen.getByText(/Generated by the local demo provider/)).toBeInTheDocument();
    expect(screen.getByText('812 ms')).toBeInTheDocument();
    expect(screen.getByText('~40')).toBeInTheDocument();
    expect(screen.getByText('estimated')).toBeInTheDocument();
    expect(calls.find((call) => call.method === 'POST')?.body).toEqual({
      model_id: 'demo-1',
      prompt: 'Hello',
      system_prompt: null,
      temperature: 0.7,
      max_tokens: 256,
      source: 'playground',
    });
  });

  it('shows a recorded upstream failure with a readable title', async () => {
    const user = userEvent.setup();
    setup(
      record({
        model_name: 'gpt-proxy',
        is_demo: false,
        status: 'error',
        response_text: null,
        error_kind: 'timeout',
        error_message: 'No response from the endpoint within 60s',
        metrics: { latency_ms: 60_000, prompt_tokens: null, completion_tokens: null, total_tokens: null, token_count_source: null, tokens_per_second: null },
      }),
    );
    renderWithProviders(<PlaygroundPage />);

    await user.selectOptions(await screen.findByRole('combobox', { name: 'Model' }), 'real-1');
    await user.type(screen.getByRole('textbox', { name: 'Prompt' }), 'Hello');
    await user.click(screen.getByRole('button', { name: 'Run inference' }));

    expect(await screen.findByText('The endpoint timed out')).toBeInTheDocument();
    expect(screen.getByText('No response from the endpoint within 60s')).toBeInTheDocument();
    expect(screen.queryByText(/Generated by the local demo provider/)).not.toBeInTheDocument();
  });
});
